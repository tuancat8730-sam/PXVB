-- Phân hệ PR – Phiên ca, sản lượng, dừng máy, đổi mác (SDD §8.1).

CREATE TABLE pr_shift_session (
    id                 BINARY(16)  NOT NULL,
    row_version        BIGINT      NOT NULL DEFAULT 0,
    created_at         DATETIME(6) NULL,
    created_by         BINARY(16)  NULL,
    updated_at         DATETIME(6) NULL,
    updated_by         BINARY(16)  NULL,
    business_date      DATE        NOT NULL,
    shift_code         VARCHAR(10) NOT NULL,
    planned_start      DATETIME(6) NOT NULL,
    planned_end        DATETIME(6) NOT NULL,
    actual_start       DATETIME(6) NULL,
    actual_end         DATETIME(6) NULL,
    status             VARCHAR(20) NOT NULL,
    leader_employee_id BINARY(16)  NULL,
    opened_by          BINARY(16)  NULL,
    closed_by          BINARY(16)  NULL,
    warnings           JSON        NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_shift_session (business_date, shift_code),
    KEY ix_shift_session_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE pr_machine_run (
    id                    BINARY(16)  NOT NULL,
    row_version           BIGINT      NOT NULL DEFAULT 0,
    session_id            BINARY(16)  NOT NULL,
    machine_id            BINARY(16)  NOT NULL,
    order_id              BINARY(16)  NULL,
    order_code            VARCHAR(50) NULL,
    status                VARCHAR(20) NOT NULL,
    planned_packs         BIGINT      NULL,
    initial_product_id    BINARY(16)  NULL,
    current_product_id    BINARY(16)  NULL,
    segment_no            INT         NOT NULL DEFAULT 1,
    planned_minutes       INT         NOT NULL,
    run_minutes           INT         NOT NULL DEFAULT 0,
    planned_stop_minutes  INT         NOT NULL DEFAULT 0,
    unplanned_stop_minutes INT        NOT NULL DEFAULT 0,
    output_qty            BIGINT      NOT NULL DEFAULT 0,
    output_count          INT         NOT NULL DEFAULT 0,
    last_counter_reading  BIGINT      NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_machine_run (session_id, machine_id),
    KEY ix_machine_run_machine (machine_id),
    CONSTRAINT fk_run_session FOREIGN KEY (session_id) REFERENCES pr_shift_session (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE pr_output_entry (
    id              BINARY(16)   NOT NULL,
    row_version     BIGINT       NOT NULL DEFAULT 0,
    created_at      DATETIME(6)  NULL,
    created_by      BINARY(16)   NULL,
    run_id          BINARY(16)   NOT NULL,
    machine_id      BINARY(16)   NOT NULL,
    product_id      BINARY(16)   NULL,
    segment_no      INT          NOT NULL,
    period_from     DATETIME(6)  NOT NULL,
    period_to       DATETIME(6)  NOT NULL,
    qty             BIGINT       NOT NULL,
    unit            VARCHAR(10)  NOT NULL,
    counter_reading BIGINT       NULL,
    note            VARCHAR(500) NULL,
    entered_by      BINARY(16)   NULL,
    on_behalf_of    BINARY(16)   NULL,
    occurred_at     DATETIME(6)  NOT NULL,
    device_id       BINARY(16)   NULL,
    PRIMARY KEY (id),
    KEY ix_output_run (run_id, period_from),
    CONSTRAINT fk_output_run FOREIGN KEY (run_id) REFERENCES pr_machine_run (id),
    CONSTRAINT ck_output_qty CHECK (qty >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE pr_stop_event (
    id                BINARY(16)   NOT NULL,
    row_version       BIGINT       NOT NULL DEFAULT 0,
    created_at        DATETIME(6)  NULL,
    created_by        BINARY(16)   NULL,
    run_id            BINARY(16)   NOT NULL,
    machine_id        BINARY(16)   NOT NULL,
    reason_code       VARCHAR(10)  NOT NULL,
    planned_downtime  BIT(1)       NOT NULL DEFAULT 0,
    start_at          DATETIME(6)  NOT NULL,
    end_at            DATETIME(6)  NULL,
    auto_closed       BIT(1)       NOT NULL DEFAULT 0,
    note              VARCHAR(500) NULL,
    tech_cause_code   VARCHAR(50)  NULL,
    tech_confirmed_by BINARY(16)   NULL,
    tech_confirmed_at DATETIME(6)  NULL,
    repair_request_id BINARY(16)   NULL,
    entered_by        BINARY(16)   NULL,
    device_id         BINARY(16)   NULL,
    open_key          BINARY(16) GENERATED ALWAYS AS (IF(end_at IS NULL, machine_id, NULL)) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stop_open_per_machine (open_key),
    KEY ix_stop_run (run_id, start_at),
    KEY ix_stop_machine (machine_id, start_at),
    CONSTRAINT fk_stop_run FOREIGN KEY (run_id) REFERENCES pr_machine_run (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE pr_product_change (
    id              BINARY(16)  NOT NULL,
    created_at      DATETIME(6) NULL,
    created_by      BINARY(16)  NULL,
    run_id          BINARY(16)  NOT NULL,
    machine_id      BINARY(16)  NOT NULL,
    from_product_id BINARY(16)  NULL,
    to_product_id   BINARY(16)  NOT NULL,
    segment_no      INT         NOT NULL,
    changed_at      DATETIME(6) NOT NULL,
    stop_event_id   BINARY(16)  NULL,
    entered_by      BINARY(16)  NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_change_segment (run_id, segment_no),
    CONSTRAINT fk_change_run FOREIGN KEY (run_id) REFERENCES pr_machine_run (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
