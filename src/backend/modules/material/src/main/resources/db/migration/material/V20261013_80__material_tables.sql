-- Phân hệ MT – Cấp phát & kiểm soát tiêu hao NVL (SDD §7.1).

CREATE TABLE mt_issue_slip (
    id                  BINARY(16)   NOT NULL,
    row_version         BIGINT       NOT NULL DEFAULT 0,
    created_at          DATETIME(6)  NULL,
    created_by          BINARY(16)   NULL,
    updated_at          DATETIME(6)  NULL,
    updated_by          BINARY(16)   NULL,
    code                VARCHAR(80)  NOT NULL,
    order_id            BINARY(16)   NOT NULL,
    order_code          VARCHAR(50)  NULL,
    business_date       DATE         NOT NULL,
    shift_code          VARCHAR(10)  NOT NULL,
    slip_type           VARCHAR(30)  NOT NULL,
    consumer_machine_id BINARY(16)   NOT NULL,
    product_id          BINARY(16)   NOT NULL,
    norm_version_id     BINARY(16)   NULL,
    revision            INT          NOT NULL DEFAULT 1,
    status              VARCHAR(20)  NOT NULL,
    confirmed_by        BINARY(16)   NULL,
    confirmed_at        DATETIME(6)  NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_issue_slip_code (code),
    UNIQUE KEY uq_issue_slip_scope (order_id, slip_type, consumer_machine_id, revision),
    KEY ix_issue_slip_shift (business_date, shift_code),
    KEY ix_issue_slip_machine (consumer_machine_id, business_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mt_issue_slip_line (
    id            BINARY(16)    NOT NULL,
    slip_id       BINARY(16)    NOT NULL,
    slot_no       INT           NOT NULL,
    material_id   BINARY(16)    NOT NULL,
    planned_qty   DECIMAL(18,3) NOT NULL,
    uom           VARCHAR(20)   NOT NULL,
    adjust_reason VARCHAR(300)  NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_slip_line (slip_id, slot_no, material_id),
    CONSTRAINT fk_slip_line FOREIGN KEY (slip_id) REFERENCES mt_issue_slip (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mt_issue_record (
    id                   BINARY(16)    NOT NULL,
    row_version          BIGINT        NOT NULL DEFAULT 0,
    created_at           DATETIME(6)   NULL,
    created_by           BINARY(16)    NULL,
    slip_id              BINARY(16)    NULL,
    slip_line_id         BINARY(16)    NULL,
    business_date        DATE          NOT NULL,
    shift_code           VARCHAR(10)   NOT NULL,
    slot_no              INT           NOT NULL,
    consumer_machine_id  BINARY(16)    NOT NULL,
    material_id          BINARY(16)    NOT NULL,
    lot_no               VARCHAR(80)   NULL,
    issued_qty           DECIMAL(18,3) NOT NULL,
    uom                  VARCHAR(20)   NOT NULL,
    issued_by            BINARY(16)    NULL,
    issued_at            DATETIME(6)   NOT NULL,
    variance_qty         DECIMAL(18,3) NULL,
    variance_reason_code VARCHAR(50)   NULL,
    variance_note        VARCHAR(500)  NULL,
    device_id            BINARY(16)    NULL,
    PRIMARY KEY (id),
    KEY ix_issue_record_scope (business_date, shift_code, consumer_machine_id, material_id),
    KEY ix_issue_record_line (slip_line_id),
    CONSTRAINT ck_issue_qty CHECK (issued_qty >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mt_receipt_confirmation (
    id                       BINARY(16)    NOT NULL,
    row_version              BIGINT        NOT NULL DEFAULT 0,
    created_at               DATETIME(6)   NULL,
    issue_record_id          BINARY(16)    NOT NULL,
    received_qty             DECIMAL(18,3) NOT NULL,
    received_by              BINARY(16)    NULL,
    received_at              DATETIME(6)   NOT NULL,
    remaining_before_receipt DECIMAL(18,3) NULL,
    status                   VARCHAR(20)   NOT NULL,
    dispute_note             VARCHAR(500)  NULL,
    resolved_by              BINARY(16)    NULL,
    resolved_at              DATETIME(6)   NULL,
    resolution_note          VARCHAR(500)  NULL,
    device_id                BINARY(16)    NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_receipt_issue (issue_record_id),
    KEY ix_receipt_status (status),
    CONSTRAINT fk_receipt_issue FOREIGN KEY (issue_record_id) REFERENCES mt_issue_record (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mt_return_record (
    id                  BINARY(16)    NOT NULL,
    created_at          DATETIME(6)   NULL,
    created_by          BINARY(16)    NULL,
    business_date       DATE          NOT NULL,
    shift_code          VARCHAR(10)   NOT NULL,
    consumer_machine_id BINARY(16)    NOT NULL,
    material_id         BINARY(16)    NOT NULL,
    qty                 DECIMAL(18,3) NOT NULL,
    reason              VARCHAR(300)  NULL,
    returned_by         BINARY(16)    NULL,
    returned_at         DATETIME(6)   NOT NULL,
    device_id           BINARY(16)    NULL,
    PRIMARY KEY (id),
    KEY ix_return_scope (business_date, shift_code, consumer_machine_id, material_id),
    CONSTRAINT ck_return_qty CHECK (qty > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mt_stock_count (
    id                  BINARY(16)    NOT NULL,
    created_at          DATETIME(6)   NULL,
    created_by          BINARY(16)    NULL,
    business_date       DATE          NOT NULL,
    shift_code          VARCHAR(10)   NOT NULL,
    consumer_machine_id BINARY(16)    NOT NULL,
    material_id         BINARY(16)    NOT NULL,
    kind                VARCHAR(20)   NOT NULL,
    counted_qty         DECIMAL(18,3) NOT NULL,
    counted_by          BINARY(16)    NULL,
    counted_at          DATETIME(6)   NOT NULL,
    note                VARCHAR(500)  NULL,
    device_id           BINARY(16)    NULL,
    PRIMARY KEY (id),
    KEY ix_count_scope (business_date, shift_code, consumer_machine_id, material_id, kind, counted_at),
    CONSTRAINT ck_count_qty CHECK (counted_qty >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE mt_consumption_summary (
    id                   BINARY(16)    NOT NULL,
    row_version          BIGINT        NOT NULL DEFAULT 0,
    session_id           BINARY(16)    NOT NULL,
    business_date        DATE          NOT NULL,
    shift_code           VARCHAR(10)   NOT NULL,
    consumer_machine_id  BINARY(16)    NOT NULL,
    material_id          BINARY(16)    NOT NULL,
    opening_qty          DECIMAL(18,3) NOT NULL,
    issued_qty           DECIMAL(18,3) NOT NULL,
    returned_qty         DECIMAL(18,3) NOT NULL,
    closing_qty          DECIMAL(18,3) NOT NULL,
    counted              BIT(1)        NOT NULL,
    actual_consumed      DECIMAL(18,3) NOT NULL,
    theoretical_consumed DECIMAL(18,3) NOT NULL,
    waste_qty            DECIMAL(18,3) NOT NULL,
    waste_pct            DECIMAL(10,3) NULL,
    threshold_pct        DECIMAL(10,3) NOT NULL,
    flag                 VARCHAR(10)   NOT NULL,
    explanation          VARCHAR(1000) NULL,
    status               VARCHAR(20)   NOT NULL,
    computed_at          DATETIME(6)   NOT NULL,
    confirmed_by         BINARY(16)    NULL,
    confirmed_at         DATETIME(6)   NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_consumption (session_id, consumer_machine_id, material_id),
    KEY ix_consumption_prev (consumer_machine_id, material_id, business_date, shift_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
